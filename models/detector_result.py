"""
DetectorResult model for Module 2 (Data Quality Detection).

Represents the output of a single detector.
"""

from dataclasses import dataclass, field
from typing import Any, Dict, List

from models.issue import Issue


@dataclass(slots=True)
class DetectorResult:
    """
    Standard output returned by every detector.

    Attributes
    ----------
    detector_name:
        Name of the detector.

    issues:
        List of detected issues.

    statistics:
        Summary statistics generated by the detector.

    execution_time:
        Detector runtime in seconds.

    success:
        Whether execution completed successfully.

    error:
        Error message if execution failed.
    """

    detector_name: str

    issues: List[Issue] = field(default_factory=list)

    statistics: Dict[str, Any] = field(default_factory=dict)

    execution_time: float = 0.0

    success: bool = True

    error: str | None = None

    @property
    def issue_count(self) -> int:
        """Return total number of detected issues."""
        return len(self.issues)

    def add_issue(self, issue: Issue) -> None:
        """Append a detected issue."""
        self.issues.append(issue)

    def update_statistics(self, **kwargs) -> None:
        """Update detector statistics."""
        self.statistics.update(kwargs)

    def to_dict(self) -> Dict[str, Any]:
        """Convert result into a serializable dictionary."""

        return {
            "detector": self.detector_name,
            "success": self.success,
            "execution_time": self.execution_time,
            "issue_count": self.issue_count,
            "statistics": self.statistics,
            "issues": [issue.to_dict() for issue in self.issues],
            "error": self.error,
        }